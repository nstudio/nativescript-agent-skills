#!/usr/bin/env node
// Renders evals/tasks.mjs into ./eval.yaml (skills on) and
// evals/baseline/eval.yaml (skills off — same tasks, empty skill dir).
// Run via evals/run.sh; both files are generated, don't edit them by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { tasks } from './tasks.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const block = (s, indent) => {
  const pad = ' '.repeat(indent);
  return '|\n' + s.replace(/\s+$/, '').split('\n').map((l) => (l.trim() ? pad + l : '')).join('\n') + '\n';
};
const q = (s) => JSON.stringify(s);

function render({ baseline }) {
  const rel = baseline ? '../../' : '';
  const out = [];
  out.push(`# GENERATED by evals/build.mjs from evals/tasks.mjs — do not edit.`);
  out.push(`# Run with evals/run.sh (sets SKILLGRADE_REPO and uses the local provider).`);
  out.push(baseline ? `# Baseline: identical tasks with NO skills installed, to measure uplift.` : `# All skills under ./skills are copied into every trial's workspace.`);
  out.push(`version: "1"`);
  if (baseline) out.push(`skill: ./empty`);
  out.push(``);
  out.push(`defaults:`);
  out.push(`  agent: command`);
  out.push(`  command: bash "$SKILLGRADE_REPO/evals/agent/claude-cli.sh"`);
  out.push(`  provider: local`);
  out.push(`  trials: 3`);
  out.push(`  timeout: 900`);
  out.push(`  threshold: 0.7`);
  out.push(`  grader_provider: anthropic`);
  out.push(``);
  out.push(`tasks:`);
  for (const t of tasks) {
    out.push(`  - name: ${t.name}`);
    out.push(`    instruction: ${block(t.instruction, 6)}`);
    if (t.workspace?.length) {
      out.push(`    workspace:`);
      for (const w of t.workspace) out.push(`      - src: ${q(rel + w.src)}\n        dest: ${q(w.dest)}`);
    }
    out.push(`    graders:`);
    out.push(`      - type: deterministic`);
    out.push(`        run: node "$SKILLGRADE_REPO/evals/graders/check.mjs" ${t.name}`);
    out.push(`        weight: 0.7`);
    out.push(`      - type: llm_rubric`);
    out.push(`        rubric: ${block(t.rubric, 10)}`);
    out.push(`        weight: 0.3`);
    out.push(``);
  }
  return out.join('\n');
}

fs.writeFileSync(path.join(root, 'eval.yaml'), render({ baseline: false }));
fs.mkdirSync(path.join(root, 'evals/baseline/empty'), { recursive: true });
fs.writeFileSync(path.join(root, 'evals/baseline/eval.yaml'), render({ baseline: true }));
console.log(`wrote eval.yaml + evals/baseline/eval.yaml (${tasks.length} tasks)`);
